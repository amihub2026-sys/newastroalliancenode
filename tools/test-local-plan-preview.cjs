const fs = require('fs');
const assert = require('assert');
const read = p => fs.readFileSync(p, 'utf8');
const dev = read('src/environments/environment.ts');
const prod = read('src/environments/environment.prod.ts');
const routes = read('src/app/app.routes.ts');
const pay = read('src/app/payment-page/payment-page.ts');
const payHtml = read('src/app/payment-page/payment-page.html');
const profile = read('src/app/profile-view/profile-view.ts');
const profileHtml = read('src/app/profile-view/profile-view.html');
const basic = read('src/app/public-profile/public-profile.html');
assert.match(dev, /demoPlanPreviewEnabled:\s*true/);
assert.match(prod, /demoPlanPreviewEnabled:\s*false/);
assert.match(prod, /paymentEnabled:\s*false/);
assert.match(routes, /path:\s*'demo-profile-view', canMatch:\s*\[\(\) => !environment\.production && environment\.demoPlanPreviewEnabled\]/);
assert.match(pay, /sessionStorage\.setItem\('astroalliance:preview-plan'/);
assert.match(payHtml, /No Payment Made/);
assert.match(pay, /previewNavigating/);
assert.match(basic, /aa-demo-preview-link/);
assert.match(basic, /profileId: profile\.code/);
assert.match(profile, /if \(this\.demoMode\) return;/);
assert.match(profile, /profile\/public\//);
assert.match(profileHtml, /DEMO PREVIEW — NO PAYMENT MADE/);
assert.match(profileHtml, /\[disabled\]="demoMode"/);
assert.doesNotMatch(pay, /payments\/orders|payments\/verify/);
console.log('PASS: test plan preview local only, no payments, no entitlement, protected backend unchanged');
